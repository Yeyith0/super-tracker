import { useEffect, useMemo, useState } from "react";
import Panel from "../../components/Panel";
import { COPYRIGHT_LINE } from "../../config";

const SOURCES = [
  { id: "npm", title: "App (npm packages)" },
  { id: "rust", title: "Desktop shell (Rust crates)" },
];

function PackageRow({ pkg, text, open, onToggle }) {
  return (
    <li className="border-b border-line last:border-b-0">
      <button
        type="button"
        aria-expanded={open}
        onClick={onToggle}
        className="hud-transition grid min-h-10 w-full grid-cols-[minmax(0,1fr)_110px_minmax(0,220px)] items-center gap-4 px-3 text-left text-[14px] transition-colors hover:bg-inset"
      >
        <span className="truncate text-text">{pkg.name}</span>
        <span className="font-mono text-[12px] text-muted">{pkg.version}</span>
        <span className="truncate font-mono text-[12px] text-text-2">{pkg.license}</span>
      </button>
      {open ? (
        <pre className="max-h-80 overflow-auto whitespace-pre-wrap border-t border-line bg-inset px-4 py-3 font-mono text-[11px] leading-relaxed text-text-2">
          {text}
        </pre>
      ) : null}
    </li>
  );
}

// Generated by scripts/generate-licenses.mjs; a static file because it is large (~1 MB of license texts).
const LICENSES_URL = "/legal/third-party-licenses.json";

/** Third-party licenses, loaded on demand when this page opens. */
export default function LicensesList() {
  const [data, setData] = useState(null);
  const [failed, setFailed] = useState(false);
  const [query, setQuery] = useState("");
  const [openKey, setOpenKey] = useState(null);

  useEffect(() => {
    let active = true;
    fetch(LICENSES_URL)
      .then((response) => (response.ok ? response.json() : Promise.reject(new Error(response.statusText))))
      .then((json) => active && setData(json))
      .catch(() => active && setFailed(true));
    return () => {
      active = false;
    };
  }, []);

  const filtered = useMemo(() => {
    if (!data) return [];
    const q = query.trim().toLowerCase();
    return q ? data.packages.filter((p) => p.name.toLowerCase().includes(q) || p.license.toLowerCase().includes(q)) : data.packages;
  }, [data, query]);

  return (
    <Panel accentTop className="px-8 py-7">
      <h2 className="text-[24px] font-bold uppercase tracking-[0.04em] text-text">Open-source licenses</h2>
      <p className="mt-3 max-w-[76ch] text-[15px] leading-relaxed text-text-2">
        Super Tracker is built with these open-source components. Each one is used under its own license, shown when you
        open a row. Everything else in the app is {COPYRIGHT_LINE}
      </p>
      <input
        type="search"
        value={query}
        onChange={(event) => setQuery(event.target.value)}
        placeholder="Filter by package or license"
        aria-label="Filter licenses"
        className="mt-5 min-h-11 w-full max-w-md border border-line-strong bg-inset px-3.5 text-[15px] text-text placeholder:text-muted"
      />
      {!data && !failed ? <p className="hud-label mt-6 text-muted">Loading…</p> : null}
      {failed ? <p className="mt-6 text-[14px] text-danger-text">The license list could not be loaded. See THIRD_PARTY_LICENSES.md in the install folder.</p> : null}
      {data
        ? SOURCES.map((source) => {
            const packages = filtered.filter((p) => p.source === source.id);
            return (
              <section key={source.id} className="mt-7">
                <h3 className="section-title">
                  {source.title} <span className="font-mono text-[12px] text-muted">· {packages.length}</span>
                </h3>
                <ul className="mt-3 border border-line">
                  {packages.map((pkg) => {
                    const key = `${pkg.source}:${pkg.name}@${pkg.version}`;
                    return (
                      <PackageRow
                        key={key}
                        pkg={pkg}
                        text={data.texts[pkg.text]}
                        open={openKey === key}
                        onToggle={() => setOpenKey(openKey === key ? null : key)}
                      />
                    );
                  })}
                  {!packages.length ? <li className="px-3 py-3 text-[14px] text-muted">No matches.</li> : null}
                </ul>
              </section>
            );
          })
        : null}
    </Panel>
  );
}
